  assert.ok(!html.includes('--dsh-theme-center'))
  assert.ok(!html.includes('--dsw-font-family'))

  const match = new RegExp('<script type="application/json" id="' + CONFIG_ELEMENT_ID + '">([\\s\\S]*?)</script>').exec(html)
  assert.ok(match, 'config carrier script must be present')
  const carried = JSON.parse(match[1])
  assert.equal(carried.preset, 'nord')
  assert.equal(carried.cardLayout, true)
  assert.equal(carried.centerContentWidth, 900)
  // No `<` may leak into the JSON block (it could close the script element).
