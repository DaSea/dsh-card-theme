  assert.ok(html.includes('--dsw-alias-bg-base:'))
  assert.ok(html.includes('--dsh-theme-canvas:'))
  assert.ok(html.includes('id="' + CONFIG_ELEMENT_ID + '"'))
  // The first-paint layout script is inlined next to the style; the content
  // width travels in that script, never in the stylesheet.
  assert.ok(/<script>\(function\(\)\{try\{var s=JSON\.parse\(localStorage\.getItem\('dsh-card-theme:selection'\)/.test(html))
  assert.ok(html.includes("document.documentElement.setAttribute('data-dsh-card-theme','')"))
