// --- 6. First-paint layout boot script -----------------------------------
check('layoutBootScript keeps the card switch and drives --dsh-chat-user-width', () => {
  const script = layoutBootScript({})
  assert.ok(script.startsWith('(function(){') && script.endsWith('})()'))
  assert.ok(script.includes("localStorage.getItem('dsh-card-theme:selection')"), 'reads the studio selection')
  assert.ok(script.includes('JSON.parse('), 'guards the stored JSON')
  assert.ok(script.includes("document.documentElement.setAttribute('data-dsh-card-theme','')"), 'sets the card attribute')
  assert.ok(script.includes('catch(e)'), 'whole body is wrapped in try/catch')
  // No center attribute mechanism any more, only the platform CSS variable.
  assert.ok(!script.includes('data-dsh-theme-center-width'))
  assert.ok(!script.includes('--dsh-theme-center'))
  // Exact center clause: saved numeric field wins (including -1 suppression),
  // otherwise the config-derived literal is used.
  const centerClause =
    'var w=typeof s.centerContentWidth==="number"?(s.centerContentWidth>=400?Math.min(2400,Math.round(s.centerContentWidth)):-1):'
  assert.ok(script.includes(centerClause), 'center width clause')
  assert.ok(
    script.includes("if(w>=400)document.documentElement.style.setProperty('" + CENTER_VAR + "',w+'px')"),
    'writes the platform variable only when a width is active',
  )
  // Host config is embedded literally: card switch + clamped width fallback.
  assert.ok(layoutBootScript({ cardLayout: true }).includes('||true)document'))
  assert.ok(layoutBootScript({}).includes('||false)document'))
  assert.ok(layoutBootScript({ centerContentWidth: 1100 }).includes('):1100;'), 'config width embedded')
  assert.ok(layoutBootScript({ centerContentWidth: -1 }).includes('):-1;'), 'unlimited embedded as -1')
  assert.ok(layoutBootScript({ centerContentWidth: 3000 }).includes('):2400;'), 'config width clamped before embedding')
  assert.ok(layoutBootScript(undefined).includes('):-1;'), 'missing config is safe')
})

check('layoutBootScript applies the config × saved-selection precedence matrix', () => {
  // Host config 1100, no saved selection -> 1100px on <html>, cards off.
  let run = runBootScript(layoutBootScript({ centerContentWidth: 1100 }))
  assert.equal(run.properties[CENTER_VAR], '1100px')
  assert.ok(!('data-dsh-card-theme' in run.attributes))
  assert.equal(run.attributes[CENTER_VAR], undefined, 'no center html attribute')

  // Saved 720 beats the config width.
  run = runBootScript(layoutBootScript({ centerContentWidth: 1100 }), { selection: { centerContentWidth: 720 } })
  assert.equal(run.properties[CENTER_VAR], '720px')

  // Saved selection alone enables the width when the config is unlimited.
  run = runBootScript(layoutBootScript({}), { selection: { centerContentWidth: 720 } })
  assert.equal(run.properties[CENTER_VAR], '720px')

  // Saved -1 suppresses an active host config (explicit "unlimited" choice).
  run = runBootScript(layoutBootScript({ centerContentWidth: 1100 }), { selection: { centerContentWidth: -1 } })
  assert.equal(run.properties[CENTER_VAR], undefined, 'saved -1 must suppress the config width')

  // Saved selection without the numeric field falls back to the config.
  run = runBootScript(layoutBootScript({ centerContentWidth: 1100 }), { selection: { cardLayout: true } })
  assert.equal(run.properties[CENTER_VAR], '1100px')
  assert.ok('data-dsh-card-theme' in run.attributes)

  // Clamping: saved 5000 -> 2400, config 3000 -> 2400.
  run = runBootScript(layoutBootScript({}), { selection: { centerContentWidth: 5000 } })
  assert.equal(run.properties[CENTER_VAR], '2400px')
  run = runBootScript(layoutBootScript({ centerContentWidth: 3000 }))
  assert.equal(run.properties[CENTER_VAR], '2400px')

  // Below 400 is "unlimited": neither saved nor config enables it.
  run = runBootScript(layoutBootScript({ centerContentWidth: 100 }))
  assert.equal(run.properties[CENTER_VAR], undefined)
  run = runBootScript(layoutBootScript({}), { selection: { centerContentWidth: 300 } })
  assert.equal(run.properties[CENTER_VAR], undefined)

  // A non-number saved value falls back to the config literal.
  run = runBootScript(layoutBootScript({ centerContentWidth: 1100 }), { selection: { centerContentWidth: '720' } })
  assert.equal(run.properties[CENTER_VAR], '1100px', 'string saved value is not a number')

  // Card switch matrix unchanged: config OR saved selection.
  assert.ok('data-dsh-card-theme' in runBootScript(layoutBootScript({ cardLayout: true })).attributes)
  assert.ok(
    'data-dsh-card-theme' in runBootScript(layoutBootScript({}), { selection: { cardLayout: true } }).attributes,
  )
  assert.ok(
    !('data-dsh-card-theme' in runBootScript(layoutBootScript({}), { selection: { cardLayout: false } }).attributes),
  )

  // Storage failures stay silent (first paint just keeps the platform defaults).
  run = runBootScript(layoutBootScript({ cardLayout: true, centerContentWidth: 1100 }), { throwOnRead: true })
  assert.ok(!('data-dsh-card-theme' in run.attributes))
  assert.equal(run.properties[CENTER_VAR], undefined)
  run = runBootScript(layoutBootScript({}), { selection: undefined })
  assert.equal(run.properties[CENTER_VAR], undefined)
})

