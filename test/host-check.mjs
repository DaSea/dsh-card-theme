// Count actual token declarations (`--token:`), not `var(--token,...)` usages:
// the inert card stylesheet references its tokens even when they are off.
function declarations(css, token) {
  return (css.match(new RegExp('(?:^|[;{])' + token + ':', 'g')) ?? []).length
}

function lightRule(css) {
  const match = /^html body\{([^}]*)\}/.exec(css)
  assert.ok(match, 'missing light selector')
  return match[1]
}

function darkRule(css) {
  const match = /html body\[data-ds-dark-theme\]\{([^}]*)\}/.exec(css)
  assert.ok(match, 'missing dark selector')
  return match[1]
}

function declarationValue(rule, token) {
  const match = new RegExp(token + ':([^;]*)').exec(rule)
  assert.ok(match, 'missing declaration ' + token)
  return match[1]
}

// Execute the generated first-paint script against a minimal DOM/localStorage
// mock and report the resulting html attributes and inline properties.
function runBootScript(script, { selection, throwOnRead } = {}) {
  const attributes = {}
  const properties = {}
  const localStorage = {
    getItem(key) {
      if (throwOnRead) throw new Error('denied')
      assert.equal(key, 'dsh-card-theme:selection')
      return selection === undefined ? null : JSON.stringify(selection)
    },
  }
  const document = {
    documentElement: {
      setAttribute(name, value) {
        attributes[name] = value
      },
      style: {
        setProperty(name, value) {
          properties[name] = value
        },
      },
    },
  }
  // eslint-disable-next-line no-new-func -- trusted script generated by this repository
  new Function('localStorage', 'document', script)(localStorage, document)
  return { attributes, properties }
}

