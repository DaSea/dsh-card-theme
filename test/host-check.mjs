check('a bad custom color cannot break index injection', () => {
  const badConfig = { preset: 'custom', centerContentWidth: 1200, light: { background: 'not-a-color' }, dark: {} }
  assert.throws(() => generateCss(badConfig), /unsupported color format/)

  const warnings = []
  const rows = indexInjectionRows(badConfig, (message, error) => warnings.push({ message, error }))
  // The config carrier and the layout boot script survive; only the style is dropped.
  assert.equal(rows.length, 2, 'carrier + boot script survive')
  assert.equal(rows[0].kind, 'global')
  assert.equal(rows[0].name, CONFIG_GLOBAL)
  assert.equal(rows[0].value.preset, 'custom')
  assert.equal(rows[0].value.centerContentWidth, 1200)
  assert.equal(rows[1].kind, 'script')
  assert.ok(rows[1].text.includes('data-dsh-card-theme'))
  assert.ok(rows[1].text.includes(CENTER_VAR))
  assert.equal(warnings.length, 1)
  assert.equal(typeof warnings[0].message, 'string')
  assert.ok(warnings[0].error instanceof Error)

  // The same guarantee holds through the registered listener, with the logger
  // as the warn sink.
  const listeners = []
  const warningsSeen = []
  const httpCtx = {
    webServer: { collectIndexInjections() { return [] } },
    logger: { warn(...args) { warningsSeen.push(args) } },
    on(event, listener) {
      listeners.push(listener)
    },
    effect() {
      throw new Error('structured path')
    },
  }
  apply({ inject(deps, callback) { callback(httpCtx) } }, badConfig)
  const table = []
  listeners[0](table, {})
  assert.equal(table.length, 2)
  assert.equal(table[0].kind, 'global')
  assert.equal(table[1].kind, 'script')
  assert.equal(warningsSeen.length, 1)
})

