check('indexInjectionRows emits global + layout boot script + style rows', () => {
  const config = { preset: 'onedark', cardLayout: true, centerContentWidth: 900 }
  const rows = indexInjectionRows(config)
  assert.equal(rows.length, 3)
  const [globalRow, scriptRow, styleRow] = rows
  assert.deepEqual(globalRow, {
    kind: 'global',
    name: CONFIG_GLOBAL,
    value: { preset: 'onedark', cardLayout: true, centerContentWidth: 900, light: {}, dark: {} },
  })
  assert.equal(CONFIG_GLOBAL, '__DSH_THEME_PLUGIN_CONFIG__')
  assert.equal(scriptRow.kind, 'script')
  assert.equal(scriptRow.placement, 'head')
  assert.equal(scriptRow.text, layoutBootScript(config))
  assert.ok(scriptRow.text.includes('data-dsh-card-theme'))
  assert.ok(scriptRow.text.includes(CENTER_VAR))
  assert.ok(scriptRow.text.includes('localStorage'))
  assert.equal(styleRow.kind, 'style')
  assert.equal(styleRow.text, generateCss(config))
  assert.ok(styleRow.text.includes('--dsw-alias-bg-base:'))
  assert.ok(styleRow.text.includes('--dsh-theme-canvas:'))
  // The content width is a script-only mechanism: no CSS token, no attribute.
  assert.ok(!styleRow.text.includes(CENTER_VAR), 'chat width must not be a CSS token')
  assert.ok(!styleRow.text.includes('data-dsh-theme-center-width'))
  assert.ok(!styleRow.text.includes('--dsh-theme-center'))
  // Rows travel over the desktop boot payload (and the static worker IPC), so
  // they must survive a JSON round trip.
  assert.deepEqual(JSON.parse(JSON.stringify(rows)), rows)
  // Every preset always yields all three rows now (the card stylesheet is inert
  // without the html attribute); stock without a wallpaper included.
  assert.equal(indexInjectionRows({ preset: 'stock' }).length, 3)
  assert.ok(indexInjectionRows({ preset: 'stock' })[2].text.includes('html[data-dsh-card-theme]'))
  // Card tokens stay out of the style when the layout is off.
  assert.ok(!indexInjectionRows({ preset: 'onedark' })[2].text.includes('--dsh-theme-canvas:'))
})

