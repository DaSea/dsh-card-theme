// --- 5. Card layout tokens ------------------------------------------------
check('card layout tokens are emitted per mode only when cardLayout is on', () => {
  const cardTokenNames = [
    '--dsh-card-theme-gap',
    '--dsh-card-theme-radius',
    '--dsh-theme-canvas',
    '--dsh-card-theme-bg',
    '--dsh-card-theme-border',
  ]
  const off = generateCss({ preset: 'onedark', light: {}, dark: {} })
  for (const token of cardTokenNames) {
    assert.equal(declarations(off, token), 0, token + ' must stay off when cardLayout is false')
  }
  const enabled = generateCss({ preset: 'onedark', cardLayout: true, light: {}, dark: {} })
  for (const token of cardTokenNames) {
    assert.equal(declarations(enabled, token), 2, token + ' must be declared for light and dark')
  }
  const light = lightRule(enabled)
  const dark = darkRule(enabled)
  assert.equal(declarationValue(light, '--dsh-card-theme-gap'), '8px')
  assert.equal(declarationValue(dark, '--dsh-card-theme-radius'), '12px')
  assert.equal(declarationValue(light, '--dsh-card-theme-bg'), '#fafafa')
  assert.equal(declarationValue(dark, '--dsh-card-theme-bg'), '#282c34')
  assert.match(declarationValue(light, '--dsh-card-theme-border'), /^rgba\(/)
  assert.notEqual(
    declarationValue(light, '--dsh-theme-canvas'),
    declarationValue(dark, '--dsh-theme-canvas'),
    'canvas differs per mode',
  )
})

